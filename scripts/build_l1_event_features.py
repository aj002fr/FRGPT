def parse_event_dt_et(event_date_str: str) -> datetime:
    # Stored as ET, may be "YYYY-MM-DDTHH:MM:SS" or "YYYY-MM-DD HH:MM:SS"
    s = str(event_date_str).replace(" ", "T")
    dt = datetime.fromisoformat(s)
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=ET)
    return dt.astimezone(ET)


def load_event_instances(event_type: str, start_date: str | None, end_date: str | None) -> list[dict[str, Any]]:
    cfg = EVENT_CONFIG[event_type]
    name = cfg["db_event_name"]
    conn = sqlite3.connect(str(settings.ECONOMIC_EVENTS_DB_PATH))
    cur = conn.cursor()

    where = ["event_name = ?", "country LIKE '%United States%'"]
    params: list[Any] = [name]
    if start_date:
        where.append("event_date >= ?")
        params.append(f"{start_date}T00:00:00")
    if end_date:
        where.append("event_date <= ?")
        params.append(f"{end_date}T23:59:59")

    sql = f"""
        SELECT event_date, actual, consensus, consensus_std_dev, previous, revised, importance, category, 'economic_events' AS source_table
        FROM {settings.ECONOMIC_EVENTS_TABLE}
        WHERE {' AND '.join(where)}
        ORDER BY event_date ASC
    """
    cur.execute(sql, params)
    rows = list(cur.fetchall())

    # Newer Bloomberg-fed releases can exist in bbg_data before the broader
    # economic_events table has been backfilled. Merge those rows so L1 stays
    # current for the live dashboard.
    bbg_where = ["db_event_name = ?"]
    bbg_params: list[Any] = [name]
    if start_date:
        bbg_where.append("timestamp >= ?")
        bbg_params.append(f"{start_date}T00:00:00")
    if end_date:
        bbg_where.append("timestamp <= ?")
        bbg_params.append(f"{end_date}T23:59:59")
    cur.execute(
        f"""
        SELECT timestamp, actual, consensus, consensus_std_dev, NULL AS previous, revised, 'high' AS importance, category, 'bbg_data' AS source_table
        FROM bbg_data
        WHERE {' AND '.join(bbg_where)}
          AND timestamp IS NOT NULL
        ORDER BY timestamp ASC
        """,
        bbg_params,
    )
    rows.extend(cur.fetchall())
    conn.close()

    out = []
    seen_dates = set()
    for (event_date, actual, consensus, consensus_std_dev, previous, revised, importance, category, source_table) in rows:
        if source_table == "bbg_data":
            raw_dt = datetime.fromisoformat(str(event_date).replace(" ", "T"))
            if raw_dt.time() == time(0, 0):
                release_time = str(cfg.get("release_time") or "08:30")
                event_date = f"{raw_dt.date().isoformat()}T{release_time}:00"
        dt_et = parse_event_dt_et(event_date)
        date_key = dt_et.strftime("%Y-%m-%d")
        if date_key in seen_dates:
            continue
        seen_dates.add(date_key)
        out.append(
            {
                "event_dt_et": dt_et,
                "event_date": date_key,
                "event_time": dt_et.strftime("%H:%M"),
                "actual": actual,
                "consensus": consensus,
                "consensus_std_dev": consensus_std_dev,
                "previous": previous,
                "revised": revised,
                "importance": importance,
                "category": category,
            }
        )
    return out


def fetch_ohlcv_1m(symbol: str, start_ts_et: datetime, end_ts_et: datetime) -> list[dict[str, Any]]:
    # Postgres stores timestamptz; pass tz-aware datetimes.
    conn = psycopg2.connect(
        host=settings.PG_HOST,
        port=settings.PG_PORT,
        dbname=settings.PG_DATABASE,
        user=settings.PG_USER,
        password=settings.PG_PASSWORD,
        cursor_factory=RealDictCursor,
    )
    cur = conn.cursor()
    cur.execute(
        f"""
        SELECT ts_event, open, high, low, close, volume
        FROM {settings.PG_OHLCV_TABLE}
        WHERE symbol = %s
          AND ts_event >= %s
          AND ts_event <= %s
        ORDER BY ts_event ASC
        """,
        (symbol, start_ts_et, end_ts_et),
    )
    rows = cur.fetchall()
    conn.close()
    return rows


def get_data_date_range(symbol: str) -> tuple[str, str] | tuple[None, None]:
    """
    Return min/max date range (YYYY-MM-DD) available in Postgres for a symbol.
    """
    conn = psycopg2.connect(
        host=settings.PG_HOST,
        port=settings.PG_PORT,
        dbname=settings.PG_DATABASE,
        user=settings.PG_USER,
        password=settings.PG_PASSWORD,
        cursor_factory=RealDictCursor,
    )
    cur = conn.cursor()
    cur.execute(
        f"""
        SELECT MIN(ts_event) AS min_ts, MAX(ts_event) AS max_ts
        FROM {settings.PG_OHLCV_TABLE}
        WHERE symbol = %s
        """,
        (symbol,),
    )
    row = cur.fetchone()
    conn.close()
    if not row or not row.get("min_ts") or not row.get("max_ts"):
        return (None, None)
    min_ts = row["min_ts"].astimezone(ET) if row["min_ts"].tzinfo else row["min_ts"].replace(tzinfo=ET)
    max_ts = row["max_ts"].astimezone(ET) if row["max_ts"].tzinfo else row["max_ts"].replace(tzinfo=ET)
    return (min_ts.strftime("%Y-%m-%d"), max_ts.strftime("%Y-%m-%d"))


def _floor_to_5m(dt: datetime) -> datetime:
    minute = (dt.minute // 5) * 5
    return dt.replace(minute=minute, second=0, microsecond=0)


def aggregate_5m(rows_1m: list[dict[str, Any]]) -> list[dict[str, Any]]:
    buckets: dict[datetime, dict[str, Any]] = {}
    order: list[datetime] = []
    for r in rows_1m:
        ts = r["ts_event"]
        if ts.tzinfo is None:
            ts = ts.replace(tzinfo=ET)
        ts_et = ts.astimezone(ET)
        b = _floor_to_5m(ts_et)
        if b not in buckets:
            buckets[b] = {
                "ts_et": b,
                "open": float(r["open"]),
                "high": float(r["high"]),
                "low": float(r["low"]),
                "close": float(r["close"]),
                "volume": float(r["volume"] or 0),
            }
            order.append(b)
        else:
            agg = buckets[b]
            agg["high"] = max(agg["high"], float(r["high"]))
            agg["low"] = min(agg["low"], float(r["low"]))
            agg["close"] = float(r["close"])
            agg["volume"] += float(r["volume"] or 0)
    order.sort()
    return [buckets[k] for k in order]


def build_arrow_price_1m(event_dt_et: datetime, rows_1m: list[dict[str, Any]]):
    _require_pyarrow()
    import pyarrow as pa

    t_rel_min: list[int] = []
    ts_et_ns: list[int] = []
    ts_utc_ns: list[int] = []
    open_: list[float] = []
    high: list[float] = []
    low: list[float] = []
    close: list[float] = []
    volume: list[float] = []

    for r in rows_1m:
        ts = r["ts_event"]
        if ts.tzinfo is None:
            ts = ts.replace(tzinfo=ET)
        ts_et = ts.astimezone(ET)
        ts_utc = ts.astimezone(timezone.utc)
        rel = int(round((ts_et - event_dt_et).total_seconds() / 60.0))
        t_rel_min.append(rel)
        ts_et_ns.append(int(ts_et.timestamp() * 1_000_000_000))
        ts_utc_ns.append(int(ts_utc.timestamp() * 1_000_000_000))
        open_.append(float(r["open"]))
        high.append(float(r["high"]))
        low.append(float(r["low"]))
        close.append(float(r["close"]))
        volume.append(float(r["volume"] or 0))

    # ret/cum stats
    ret_1m: list[float] = []
    cum_ret: list[float] = []
    cum_var: list[float] = []
    c_ret = 0.0
    c_var = 0.0
    prev = None
    for px in close:
        if prev is None or prev <= 0 or px <= 0:
            r = 0.0
        else:
            r = float(math.log(px / prev))
        prev = px
        c_ret += r
        c_var += r * r
        ret_1m.append(r)
        cum_ret.append(c_ret)
        cum_var.append(c_var)

    schema = pa.schema(
        [
            ("t_rel_min", pa.int32()),
            ("ts_et_ns", pa.int64()),
            ("ts_utc", pa.int64()),
            ("open", pa.float64()),
            ("high", pa.float64()),
            ("low", pa.float64()),
            ("close", pa.float64()),
            ("volume", pa.float64()),
            ("open_dec", pa.float64()),
            ("high_dec", pa.float64()),
            ("low_dec", pa.float64()),
            ("close_dec", pa.float64()),
            ("ret_1m", pa.float32()),
            ("cum_ret", pa.float32()),
            ("cum_var", pa.float32()),
        ]
    )

    table = pa.Table.from_arrays(
        [
            pa.array(t_rel_min, type=pa.int32()),
            pa.array(ts_et_ns, type=pa.int64()),
            pa.array(ts_utc_ns, type=pa.int64()),
            pa.array(open_, type=pa.float64()),
            pa.array(high, type=pa.float64()),
            pa.array(low, type=pa.float64()),
            pa.array(close, type=pa.float64()),
            pa.array(volume, type=pa.float64()),
            pa.array(open_, type=pa.float64()),
            pa.array(high, type=pa.float64()),
            pa.array(low, type=pa.float64()),
            pa.array(close, type=pa.float64()),
            pa.array(ret_1m, type=pa.float32()),
            pa.array(cum_ret, type=pa.float32()),
            pa.array(cum_var, type=pa.float32()),
        ],
        schema=schema,
    )
    return table


