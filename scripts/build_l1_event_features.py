def build_stats_table(event_dt_et: datetime, rows_1m: list[dict[str, Any]]):
    """
    Build a compact stats table for fast slicing (optional).
    """
    _require_pyarrow()
    import pyarrow as pa
    from src.servers.analytics.schema import decimal_to_bps

    t_rel_min: list[int] = []
    ts_et_ns: list[int] = []
    close: list[float] = []
    cum_ret: list[float] = []
    cum_var: list[float] = []

    # compute close list and time arrays
    for r in rows_1m:
        ts = r["ts_event"]
        if ts.tzinfo is None:
            ts = ts.replace(tzinfo=ET)
        ts_et = ts.astimezone(ET)
        rel = int(round((ts_et - event_dt_et).total_seconds() / 60.0))
        t_rel_min.append(rel)
        ts_et_ns.append(int(ts_et.timestamp() * 1_000_000_000))
        close.append(float(r["close"]))

    # compute cum_ret/cum_var
    c_ret = 0.0
    c_var = 0.0
    prev = None
    for px in close:
        if prev is None or prev <= 0 or px <= 0:
            r = 0.0
        else:
            r = float(math.log(px / prev))
        prev = px
        c_ret += r
        c_var += r * r
        cum_ret.append(c_ret)
        cum_var.append(c_var)

    # normalize to event-time close (closest t_rel_min to 0)
    if close:
        idx_event = min(range(len(t_rel_min)), key=lambda i: abs(t_rel_min[i]))
        price_event = close[idx_event]
    else:
        price_event = None

    norm_px_bps: list[float] = []
    for px in close:
        if price_event:
            norm_px_bps.append(float(decimal_to_bps(px - price_event)))
        else:
            norm_px_bps.append(0.0)

    schema = pa.schema(
        [
            ("t_rel_min", pa.int32()),
            ("ts_et_ns", pa.int64()),
            ("close", pa.float64()),
            ("cum_ret", pa.float32()),
            ("cum_var", pa.float32()),
            ("norm_px_bps", pa.float32()),
        ]
    )
    table = pa.Table.from_arrays(
        [
            pa.array(t_rel_min, type=pa.int32()),
            pa.array(ts_et_ns, type=pa.int64()),
            pa.array(close, type=pa.float64()),
            pa.array(cum_ret, type=pa.float32()),
            pa.array(cum_var, type=pa.float32()),
            pa.array(norm_px_bps, type=pa.float32()),
        ],
        schema=schema,
    )
    return table


def write_arrow(path: Path, table) -> None:
    _require_pyarrow()
    import pyarrow as pa
    import pyarrow.ipc as ipc

    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with pa.OSFile(str(tmp), "wb") as sink:
        with ipc.new_file(sink, table.schema) as writer:
            writer.write_table(table)
    tmp.replace(path)


def write_json(path: Path, obj: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(obj, f, indent=2, default=str)
    tmp.replace(path)


def load_same_day_annotations(event_date: str) -> list[dict[str, Any]]:
    conn = sqlite3.connect(str(settings.ECONOMIC_EVENTS_DB_PATH))
    cur = conn.cursor()
    start = f"{event_date}T00:00:00"
    end = f"{event_date}T23:59:59"
    cur.execute(
        f"""
        SELECT event_name, country, category, importance, event_date
        FROM {settings.ECONOMIC_EVENTS_TABLE}
        WHERE event_date >= ? AND event_date <= ?
        ORDER BY event_date ASC
        """,
        (start, end),
    )
    rows = cur.fetchall()
    conn.close()
    out = []
    for name, country, category, importance, event_date in rows:
        out.append(
            {
                "event_name": name,
                "country": country,
                "category": category,
                "importance": importance,
                "event_date": event_date,
            }
        )
    return out


def build_one_event(event_type: str, symbol: str, window_days: int, event: dict[str, Any], force: bool) -> None:
    event_dt_et: datetime = event["event_dt_et"]
    event_date = event["event_date"]

    paths = get_event_paths(event_type, event_date)
    if not force and paths.meta.exists() and paths.price_1m.exists() and paths.price_5m.exists():
        return

    start = event_dt_et - timedelta(days=window_days)
    end = event_dt_et + timedelta(days=window_days)

    rows_1m = fetch_ohlcv_1m(symbol, start, end)
    if not rows_1m:
        return

    table_1m = build_arrow_price_1m(event_dt_et, rows_1m)
    rows_5m = aggregate_5m(rows_1m)
    table_5m = build_arrow_price_5m(event_dt_et, rows_5m)
    table_stats = build_stats_table(event_dt_et, rows_1m)

    # Precompute be_by_time (3pm prior trading day -> event time, 30-min steps)
    prev_day = event_dt_et - timedelta(days=1)
    while prev_day.weekday() >= 5:
        prev_day -= timedelta(days=1)
    start_3pm = prev_day.replace(hour=15, minute=0, second=0, microsecond=0)
    end_event = event_dt_et

    # Build a cumulative max/min from 3pm onward for O(1) window end-times
    rows_in_window = [
        r for r in rows_1m
        if (r["ts_event"].astimezone(ET) if r["ts_event"].tzinfo else r["ts_event"].replace(tzinfo=ET)) >= start_3pm
        and (r["ts_event"].astimezone(ET) if r["ts_event"].tzinfo else r["ts_event"].replace(tzinfo=ET)) <= end_event
    ]
    rows_in_window.sort(key=lambda r: r["ts_event"])
    price_3pm = float(rows_in_window[0]["close"]) if rows_in_window else None

    be_by_time: dict[str, float] = {}
    bps_by_time: dict[str, float] = {}
    if price_3pm and rows_in_window:
        running_high = None
        running_low = None
        idx = 0
        total = len(rows_in_window)
        # Compute for each half-hour between 15:00 prev day and event time
        t = start_3pm
        while t <= end_event:
            # advance rows up to t
            while idx < total:
                ts = rows_in_window[idx]["ts_event"]
                ts_et = ts.astimezone(ET) if ts.tzinfo else ts.replace(tzinfo=ET)
                if ts_et > t:
                    break
                hi = float(rows_in_window[idx]["high"])
                lo = float(rows_in_window[idx]["low"])
                running_high = hi if running_high is None else max(running_high, hi)
                running_low = lo if running_low is None else min(running_low, lo)
                idx += 1

            if running_high is not None and running_low is not None:
                up_move = abs(running_high - price_3pm)
                down_move = abs(price_3pm - running_low)
                max_extent = max(up_move, down_move)
                # Use 32nds convention from analytics schema
                from src.servers.analytics.schema import decimal_to_bps
                move_bps = decimal_to_bps(max_extent)
                # Store bps and BE multiplier placeholder (fwd handled at runtime)
                be_by_time[t.strftime("%H:%M")] = round(move_bps, 4)
                bps_by_time[t.strftime("%H:%M")] = round(move_bps, 4)
            t += timedelta(minutes=30)

    build_version = datetime.utcnow().strftime("%Y%m%dT%H%M%SZ")
    event_ts_utc = int(event_dt_et.astimezone(timezone.utc).timestamp() * 1_000_000_000)
    meta = {
        "event_type": event_type,
        "instrument": symbol,
        "event_name": EVENT_CONFIG[event_type]["db_event_name"],
        "date": event_date,
        "event_ts_utc": event_ts_utc,
        "event_ts_et": event_dt_et.isoformat(),
        "event_ts_et_label": event_dt_et.strftime("%Y-%m-%d %H:%M ET"),
        "event_date": event_date,
        "event_time": event["event_time"],
        "timezone": "America/New_York",
        "window_days": window_days,
        "build_version": build_version,
        "available_resolutions": ["1m", "5m"],
        "validation": {"is_sorted": True, "bad_tick_filtered": False},
        "source": {
            "postgres_table": settings.PG_OHLCV_TABLE,
            "postgres_host": settings.PG_HOST,
            "postgres_db": settings.PG_DATABASE,
        },
        "row_counts": {"price_1m": table_1m.num_rows, "price_5m": table_5m.num_rows},
        "economic": {
            "actual": event.get("actual"),
            "consensus": event.get("consensus"),
            "consensus_std_dev": event.get("consensus_std_dev"),
            "previous": event.get("previous"),
            "revised": event.get("revised"),
        },
        "precomputed": {
            "be_by_time": be_by_time,
            "bps_by_time": bps_by_time,
            "price_3pm": price_3pm,
        },
        "annotations_same_day": load_same_day_annotations(event_date),
        "schema_version": 1,
    }

    write_json(paths.meta, meta)
    write_arrow(paths.price_1m, table_1m)
    write_arrow(paths.price_5m, table_5m)
    write_arrow(paths.stats, table_stats)


def main() -> int:
    parser = argparse.ArgumentParser(description="Build L1 event features (TY-only) to local Arrow files")
    parser.add_argument("--event", required=True, choices=["NFP", "CPI", "PPI", "JOLTS"])
    parser.add_argument("--symbol", default="TY", help="Instrument symbol in ohlcv_1m (default: TY)")
    parser.add_argument("--window-days", type=int, default=7, help="Days before/after event to bake (default: 7)")
    parser.add_argument("--start-date", default=None, help="YYYY-MM-DD (optional)")
    parser.add_argument("--end-date", default=None, help="YYYY-MM-DD (optional)")
    parser.add_argument(
        "--auto-range",
        action="store_true",
        help="Use min/max dates from Postgres for the symbol (overrides start/end if provided)",
    )
    parser.add_argument("--force", action="store_true", help="Rebuild even if files exist")
    args = parser.parse_args()

    event_type = args.event.upper()

    if not settings.ECONOMIC_EVENTS_DB_PATH.exists():
        print(f"ERROR: missing SQLite DB: {settings.ECONOMIC_EVENTS_DB_PATH}")
        return 2

    # Ensure base directory exists
    (get_l1_root() / event_type).mkdir(parents=True, exist_ok=True)

    # Try import pyarrow early for fast failure
    _require_pyarrow()

    start_date = args.start_date
    end_date = args.end_date
    if args.auto_range or (start_date is None and end_date is None):
        db_min, db_max = get_data_date_range(args.symbol)
        if db_min and db_max:
            start_date = db_min
            end_date = db_max
        else:
            print("ERROR: Could not determine data range from Postgres. Provide --start-date/--end-date.")
            return 2

    events = load_event_instances(event_type, start_date, end_date)
    if start_date and end_date:
        print(f"[L1] Date range: {start_date} → {end_date} (from {'auto' if args.auto_range else 'args'})")
    print(f"[L1] Found {len(events)} {event_type} events in SQLite")

    built = 0
    skipped = 0
    for ev in events:
        before = get_event_paths(event_type, ev["event_date"]).price_1m.exists()
        build_one_event(event_type, args.symbol, args.window_days, ev, force=args.force)
        after = get_event_paths(event_type, ev["event_date"]).price_1m.exists()
        if after and (args.force or not before):
            built += 1
        else:
            skipped += 1

    print(f"[L1] Done. built={built} skipped={skipped} out_dir={get_l1_root() / event_type}")
    return 0


